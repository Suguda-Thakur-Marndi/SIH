// Write all 14 language files
for (const lang of Object.keys(translations)) {
  const filePath = path.join(TRANSLATIONS_DIR, `${lang}.ts`);
  const dict = translations[lang];
  
  let content = `export const ${lang}: Record<string, string> = {\n`;
  for (const [k, v] of Object.entries(dict)) {
    // Escape single quotes
    const safeV = v.replace(/'/g, "\\'").replace(/\n/g, '\\n');
    content += `  ${k}: '${safeV}',\n`;
  }
  content += `};\n`;
  
  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Updated [${lang}.ts] with ${Object.keys(dict).length} keys.`);
}
