const languages = ['en', 'hi', 'or', 'bn', 'te', 'ta', 'mr', 'gu', 'pa', 'kn', 'ml', 'as', 'ur', 'ne'];

// First run build_full_dictionaries.js logic
require('./build_full_dictionaries.js');

for (const lang of languages) {
  const filePath = path.join(translationsDir, `${lang}.ts`);
  if (!fs.existsSync(filePath)) continue;

  let content = fs.readFileSync(filePath, 'utf8');
  
  // Fix any malformed dont_have_account or string issues
  content = content.replace(/dont_have_account:\s*'[^']*'t have an account\?',/g, "dont_have_account: \"Don't have an account?\",");
  
  const overrides = languageOverrides[lang] || {};
  for (const [k, v] of Object.entries(overrides)) {
    const keyRegex = new RegExp(`^\\s*${k}:\\s*.*$`, 'm');
    const safeVal = JSON.stringify(v);
    if (keyRegex.test(content)) {
      content = content.replace(keyRegex, `  ${k}: ${safeVal},`);
    } else {
      content = content.replace(/(\n\};\s*$)/, `  ${k}: ${safeVal},\n$1`);
    }
  }

  // Ensure valid string literals
  content = content.replace(/dont_have_account:\s*'Don't have an account\?',/g, "dont_have_account: \"Don't have an account?\",");

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Cleanly patched ${lang}.ts`);
}

