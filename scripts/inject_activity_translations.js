langs.forEach(lang => {
  const filePath = path.join(transDir, `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  const startIdx = content.indexOf('{');
  const endIdx = content.lastIndexOf('}');
  if (startIdx === -1 || endIdx === -1) return;

  let dict = JSON.parse(content.substring(startIdx, endIdx + 1));
  let count = 0;
  for (const [k, v] of Object.entries(activityTranslations)) {
    dict[k] = v[lang] || v['en'] || k;
    count++;
  }

  const updatedCode = `export const ${lang}: Record<string, string> = ${JSON.stringify(dict, null, 2)};\n`;
  fs.writeFileSync(filePath, updatedCode, 'utf8');
  console.log(`✓ Added activity keys to ${lang}.ts (+${count})`);
});
