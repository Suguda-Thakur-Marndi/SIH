// Fallback maps: which defined language to use for undefined languages
const FALLBACK = {
  bn: 'hi', mr: 'hi', gu: 'hi', pa: 'hi', ne: 'hi', ur: 'hi',
  ta: 'te', kn: 'te', ml: 'te', as: 'or'
};

function getExistingKeys(lang) {
  const filePath = path.join(TRANSLATIONS_DIR, `${lang}.ts`);
  const content = fs.readFileSync(filePath, 'utf8');
  const keys = new Set();
  const keyRegex = /^\s+"([^"]+)":/gm;
  let m;
  while ((m = keyRegex.exec(content)) !== null) {
    keys.add(m[1]);
  }
  return keys;
}

function appendKeysToFile(lang, newKeys) {
  const filePath = path.join(TRANSLATIONS_DIR, `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');
  
  const existingKeys = getExistingKeys(lang);
  
  const newEntries = [];
  for (const [key, value] of Object.entries(newKeys)) {
    if (!existingKeys.has(key)) {
      // Escape any double quotes in value
      const safeValue = value.replace(/"/g, '\\"');
      newEntries.push(`  "${key}": "${safeValue}"`);
    }
  }
  
  if (newEntries.length === 0) {
    console.log(`✓ ${lang}.ts - all keys already exist`);
    return;
  }
  
  // Find the last }; in the file and insert before it
  const lastBrace = content.lastIndexOf('\n};');
  if (lastBrace === -1) {
    console.error(`✗ Cannot find closing }; in ${lang}.ts`);
    return;
  }
  
  // Check if the char before }; is a comma - if not, add one
  const beforeBrace = content.slice(0, lastBrace);
  const lastNonWhitespace = beforeBrace.trimEnd();
  const needsComma = !lastNonWhitespace.endsWith(',');
  
  const separator = needsComma ? ',\n' : '\n';
  const newContent = content.slice(0, lastBrace) + separator + newEntries.join(',\n') + content.slice(lastBrace);
  
  fs.writeFileSync(filePath, newContent, 'utf8');
  console.log(`✓ ${lang}.ts - added ${newEntries.length} new keys`);
}

// Process all languages
for (const lang of ALL_LANGS) {
  const keysToUse = KEYS[lang] || KEYS[FALLBACK[lang]] || KEYS.en;
  appendKeysToFile(lang, keysToUse);
}

