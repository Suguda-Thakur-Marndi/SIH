// Update translation files
const LANG_DIR = path.join(__dirname, '..', 'lib', 'translations');

for (const [lang, dict] of Object.entries(TRANSLATION_MAP)) {
  const filePath = path.join(LANG_DIR, `${lang}.ts`);
  if (!fs.existsSync(filePath)) continue;

  let content = fs.readFileSync(filePath, 'utf8');
  let updated = 0;

  for (const [key, val] of Object.entries(dict)) {
    const escapedVal = val.replace(/'/g, "\\'");
    // Match either 'key': '...' or "key": "..."
    const keyRegex = new RegExp(`(['"]${key}['"]\\s*:\\s*)(['"][^'"]*['"])`, 'g');
    if (keyRegex.test(content)) {
      content = content.replace(keyRegex, `$1'${escapedVal}'`);
      updated++;
    } else {
      // Append key before closing bracket
      const insertPoint = content.lastIndexOf('};');
      if (insertPoint !== -1) {
        content = content.slice(0, insertPoint) + `  '${key}': '${escapedVal}',\n` + content.slice(insertPoint);
        updated++;
      }
    }
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`✅ Updated ${updated} keys in ${lang}.ts`);
}
